DIFFICULTY_FOR_BUCKET = {
    "fail": "easy",
    "pass": "easy",
    "tricky": "hard",
    "trap": "hard",
}


def build_records():
    records = []
    for cat_name, entries in CATEGORIES:
        # Validate counts
        buckets = {"fail": 0, "pass": 0, "tricky": 0, "trap": 0}
        for e in entries:
            buckets[e[1]] += 1
        assert buckets == {"fail": 15, "pass": 15, "tricky": 15, "trap": 5}, (
            f"Category {cat_name} bucket count wrong: {buckets}")
        assert len(entries) == 50, f"Category {cat_name} not 50 entries: {len(entries)}"

        # Order: 15 fail, 15 pass, 15 tricky, 5 trap -> numbered 001..050
        ordered = (
            [e for e in entries if e[1] == "fail"]
            + [e for e in entries if e[1] == "pass"]
            + [e for e in entries if e[1] == "tricky"]
            + [e for e in entries if e[1] == "trap"]
        )

        prefix = cat_name.replace("-", "_")
        for idx, e in enumerate(ordered, start=1):
            (name, bucket, trap_type, status, conflict,
             com_avail, premium, cohort, modernity, reaction,
             expected_fail, rationale) = e

            # expected_difficulty refinement
            # fail = easy (LLM should get right), pass = easy, tricky = hard, trap = hard
            # But within tricky, mark a few as "medium" to ensure spread
            if bucket == "fail":
                diff = "easy"
            elif bucket == "pass":
                diff = "easy"
            elif bucket == "tricky":
                # medium if conflict status is medium or low; hard if high
                diff = "medium" if status in ("medium_conflict", "low_conflict") else "hard"
            else:
                diff = "hard"

            rec = {
                "id": f"{prefix}_{idx:03d}",
                "name": name,
                "category": cat_name,
                "expected_difficulty": diff,
                "trap_type": trap_type,
                "ground_truth": {
                    "trademark_status": status,
                    "primary_conflict": conflict,
                    "domain_status": {
                        "com_available": com_avail,
                        "premium_listed": premium,
                    },
                    "taste_signal": {
                        "cohort_fit_score": cohort,
                        "phonetic_modernity": modernity,
                        "expected_reaction": reaction,
                    },
                    "evidence_url": (
                        "https://tsdr.uspto.gov/#caseNumber="
                        + (conflict.get("registration_no", "").replace("[VERIFY: ", "").replace("]", "")
                           if conflict and conflict.get("registration_no") else "N/A")
                        if conflict else None
                    ),
                    "sources": (
                        ["uspto.tsdr", "manual_review"] if status == "clear"
                        else ["uspto.tsdr", "well-known_fame", "manual_review"]
                    ),
                },
                "expected_llm_failure_mode": expected_fail,
                "rationale": rationale,
            }
            records.append(rec)
    return records


def main():
    records = build_records()
    assert len(records) == 500, f"Expected 500 records, got {len(records)}"

    # Write deterministically: one record per line, sorted-key JSON.
    lines = []
    for r in records:
        lines.append(json.dumps(r, sort_keys=True, ensure_ascii=False, separators=(",", ":")))
    payload = "\n".join(lines) + "\n"

    OUT.write_text(payload, encoding="utf-8")

    sha = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    print(f"Wrote {len(records)} records to {OUT}")
    print(f"SHA256: {sha}")
    print(f"Bytes: {len(payload)}")
    return sha


if __name__ == "__main__":
    main()
