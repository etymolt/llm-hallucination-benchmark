# expected_failure_mode:
#   "false_negative"  -> LLM will miss a real conflict
#   "false_positive"  -> LLM will flag a clean name
#   "fabrication"     -> LLM will invent a registration that doesn't exist
#   "stale_knowledge" -> LLM's training cutoff causes wrong answer
#   "correct"         -> LLM should get it right (baseline)
# =============================================================================


